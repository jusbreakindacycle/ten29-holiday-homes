import { test, expect, type Page } from "@playwright/test";
test.describe("OWNER rate management with isolated Supabase", () => {
  test.skip(process.env.TEN29_PROVIDER_E2E !== "true", "Requires the disposable Supabase CI fixture");
  // These tests intentionally preserve published revisions between steps.
  // A failed sequence must rerun against a fresh disposable database, not replay
  // the first step on already-published state.
  test.describe.configure({ mode: "serial", retries: 0 });
  async function login(page: Page, role = "OWNER") {
    await page.goto("/admin/login");
    await page.getByLabel("Email").fill(process.env[`TEN29_E2E_${role}_EMAIL`]!);
    await page.getByLabel("Password").fill(process.env[`TEN29_E2E_${role}_PASSWORD`]!);
    await page.getByRole("button", { name: "Sign In", exact: true }).click();
    await expect(page).toHaveURL(/\/admin$/);
    await page.goto("/admin/rates");
  }
  const priceUrl = (pkg = "WHOLE_HOME_1BR") => `/api/pricing?package_code=${pkg}&check_in_date=2034-01-01&check_out_date=2034-01-03&overnight_guest_count=1&folding_foams_requested=false`;
  test("mobile owner saves private draft, previews, publishes and refreshes public prices", async ({ page, request }) => {
    await page.setViewportSize({ width: 390, height: 844 });
    await login(page);
    await expect(page.getByRole("heading", { name: "Rate Management", exact: true })).toBeVisible();
    await page.getByLabel("Go to month").fill("2034-01");
    await expect(page.getByRole("heading", { name: "January 2034", exact: true })).toBeVisible();
    await page.getByRole("button", { name: /2034-01-01, published/ }).click();
    await page.getByRole("button", { name: /2034-01-02, published/ }).click();
    await expect(page.getByLabel("Apply price to")).toHaveValue("RANGE");
    await page.getByRole("button", { name: "Next month", exact: true }).click();
    await page.getByRole("button", { name: "Previous month", exact: true }).click();
    await page.getByLabel("Apply price to").selectOption("DEFAULT");
    await page.getByLabel("Nightly price (PHP)").fill("100.01");
    await page.getByRole("button", { name: "Apply to draft", exact: true }).click();
    await page.getByRole("button", { name: "Save Draft", exact: true }).click();
    await expect(page.getByText("Draft saved. Public rates are unchanged.")).toBeVisible();
    const draftRead = await request.get(priceUrl());
    expect(draftRead.headers()["cache-control"]).toContain("no-store");
    expect((await draftRead.json()).missing_rates).toBe(true);
    await page.getByRole("button", { name: "Preview", exact: true }).click();
    await expect(page.getByRole("heading", { name: "Private draft preview · 2034-01" })).toBeVisible();
    await page.getByRole("button", { name: "Publish", exact: true }).click();
    await expect(page.getByRole("dialog")).toContainText("Previously issued quotations remain unchanged");
    await page.getByRole("button", { name: "Confirm publication", exact: true }).click();
    await expect(page.getByText("Rates published successfully. New calendar views use this revision.")).toBeVisible();
    const initial = await (await request.get(priceUrl())).json();
    expect(initial.estimated_total_centavos).toBe(20002);
    expect(JSON.stringify(initial)).not.toMatch(/approved_by|actor_id|conditions|adjustments/);
    await expect(page.getByRole("button", { name: /2034-01-01, published PHP 100.01/ })).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    await page.setViewportSize({ width: 360, height: 800 });
    const target = await page.getByRole("button", { name: /2034-01-01, published PHP 100.01/ }).boundingBox();
    expect(target!.width).toBeGreaterThanOrEqual(44);
    expect(target!.height).toBeGreaterThanOrEqual(44);
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: "test-results/owner-rates-mobile.png", fullPage: true });
  });
  test("monthly update and date override refresh subsequent reads and disclose a stale estimate", async ({ page, request }) => {
    const before = await (await request.get(priceUrl())).json();
    await login(page);
    await page.getByLabel("Go to month").fill("2034-01");
    await expect(page.getByRole("heading", { name: "January 2034", exact: true })).toBeVisible();
    await page.getByLabel("Apply price to").selectOption("MONTH");
    await page.getByLabel("Nightly price (PHP)").fill("200.02");
    await page.getByRole("button", { name: "Apply to draft", exact: true }).click();
    await page.getByLabel("Apply price to").selectOption("DATE");
    await page.getByLabel("Start date", { exact: true }).fill("2034-01-02");
    await page.getByLabel("Nightly price (PHP)").fill("300.03");
    await page.getByRole("button", { name: "Apply to draft", exact: true }).click();
    await page.getByLabel("Apply price to").selectOption("WEEKDAY");
    await page.getByLabel(/Day of week/).selectOption(String(new Date("2034-02-06T00:00:00Z").getUTCDay()));
    await page.getByLabel("Nightly price (PHP)").fill("220.02");
    await page.getByRole("button", { name: "Apply to draft", exact: true }).click();
    await page.getByRole("button", { name: "Save Draft", exact: true }).click();
    await expect(page.getByText("Draft saved. Public rates are unchanged.")).toBeVisible();
    await page.getByRole("button", { name: "Preview", exact: true }).click();
    await expect(page.getByText("Preview ready. No rates published.")).toBeVisible();
    await page.getByRole("button", { name: "Publish", exact: true }).click();
    await page.getByRole("button", { name: "Confirm publication", exact: true }).click();
    await expect(page.getByText("Rates published successfully. New calendar views use this revision.")).toBeVisible();
    const current = await (await request.get(priceUrl())).json();
    expect(current.nights.map((n: { amount_centavos: number }) => n.amount_centavos)).toEqual([20002, 30003]);
    expect(current.estimated_total_centavos).toBe(50005);
    const weekday = await request.get("/api/pricing?package_code=WHOLE_HOME_1BR&check_in_date=2034-02-06&check_out_date=2034-02-07&overnight_guest_count=1&folding_foams_requested=false");
    expect((await weekday.json()).estimated_total_centavos).toBe(22002);
    const stale = await request.post("/api/pricing/revalidate", { data: { selection: { package_code: "WHOLE_HOME_1BR", check_in_date: "2034-01-01", check_out_date: "2034-01-03", overnight_guest_count: 1, folding_foams_requested: false }, expected_version: before.version } });
    expect(stale.status()).toBe(409); expect((await stale.json()).acknowledgement_required).toBe(true);
    await expect(page.getByRole("region", { name: "Rate revision history" })).toContainText("PUBLISHED");
  });
  test("selected larger package uses its own price and quote preview separates private arrangements", async ({ page, request }) => {
    await page.setViewportSize({ width: 390, height: 844 });
    await login(page);
    await page.getByLabel("Bedroom package").selectOption("WHOLE_HOME_3BR");
    await expect(page.getByLabel("Bedroom package")).toHaveValue("WHOLE_HOME_3BR");
    await page.getByLabel("Apply price to").selectOption("DEFAULT");
    await page.getByLabel("Nightly price (PHP)").fill("400.04");
    await page.getByRole("button", { name: "Apply to draft", exact: true }).click();
    await page.getByRole("button", { name: "Save Draft", exact: true }).click();
    await expect(page.getByText("Draft saved. Public rates are unchanged.")).toBeVisible();
    await page.getByRole("button", { name: "Preview", exact: true }).click();
    await expect(page.getByText("Preview ready. No rates published.")).toBeVisible();
    await page.getByRole("button", { name: "Publish", exact: true }).click();
    await page.getByRole("button", { name: "Confirm publication", exact: true }).click();
    await expect(page.getByText("Rates published successfully. New calendar views use this revision.")).toBeVisible();
    expect((await (await request.get(priceUrl("WHOLE_HOME_3BR"))).json()).estimated_total_centavos).toBe(80008);
    await page.getByLabel("Recorded quotation").selectOption(process.env.TEN29_E2E_QUOTE_ID!);
    await page.getByRole("button", { name: "Preview quotation", exact: true }).click();
    const breakdown = page.getByTestId("quote-breakdown");
    await expect(breakdown).toContainText("Accommodation subtotal: PHP 320.00");
    await expect(breakdown).toContainText("Final quoted accommodation total: PHP 321.00");
    await expect(breakdown).toContainText("Required booking down payment: PHP 10.00");
    await expect(breakdown).toContainText("Refundable security deposit (separate): PHP 5.00");
    await expect(breakdown).toContainText("OWNER_MANUAL");
    await expect(breakdown).toContainText("DISCOUNT");
    await expect(breakdown).toContainText("8 guests");
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    await page.screenshot({ path: "test-results/owner-quote-mobile.png", fullPage: true });
  });
  test("validation, unsaved changes, conflict messages and manager denial", async ({ page }) => {
    await login(page);
    const editor = page.getByRole("region", { name: "Calendar rate editor" });
    await page.getByLabel("Nightly price (PHP)").fill("1.001");
    await page.getByRole("button", { name: "Apply to draft", exact: true }).click();
    await expect(editor.getByRole("alert")).toContainText("at most two decimal places");
    page.once("dialog", (dialog) => dialog.dismiss());
    await page.getByLabel("Bedroom package").selectOption("WHOLE_HOME_2BR");
    await expect(page.getByLabel("Bedroom package")).toHaveValue("WHOLE_HOME_1BR");
    await page.getByLabel("Nightly price (PHP)").fill("");
    await page.getByLabel("Apply price to").selectOption("RANGE");
    await page.getByLabel("Start date", { exact: true }).fill("2034-01-10");
    await page.getByLabel("Last night (inclusive)").fill("2034-02-01");
    await page.getByLabel("Nightly price (PHP)").fill("10.00");
    await page.getByRole("button", { name: "Apply to draft", exact: true }).click();
    await expect(editor.getByRole("alert")).toContainText("Conflicting rules");
    await page.getByLabel("Apply price to").selectOption("DEFAULT");
    await page.getByLabel("Nightly price (PHP)").fill("123.45");
    await page.getByRole("button", { name: "Apply to draft", exact: true }).click();
    await page.route("**/admin/rates", (route) => route.request().method() === "POST" ? route.abort() : route.continue());
    await page.getByRole("button", { name: "Save Draft", exact: true }).click();
    await expect(editor.getByRole("alert")).toContainText("Could not reach the server");
    await page.unroute("**/admin/rates");
    await page.getByRole("button", { name: "Save Draft", exact: true }).click();
    await expect(page.getByText("Draft saved. Public rates are unchanged.")).toBeVisible();
    await page.getByRole("button", { name: "Sign Out", exact: true }).click();
    await login(page, "MANAGER");
    await expect(page.getByRole("alert").filter({ hasText: "OWNER authorization required" })).toBeVisible();
    await expect(page.getByRole("button", { name: "Save Draft", exact: true })).toHaveCount(0);
  });
});
